"""Anomaly detection over business time series.

Three methods are available, and the choice between them is made from the shape
of the data rather than applied uniformly:

``rolling_zscore``
    Compares each point with a trailing window. This is the default because
    business series drift — a "normal" Tuesday in December is not a normal
    Tuesday in June, and a global threshold would flag an entire growing quarter.

``iqr``
    Robust to outliers and makes no distributional assumption. Used for short
    series where a rolling window cannot be formed.

``isolation_forest``
    Multivariate, used only when several correlated metrics are available and
    the series is long enough to train on. It can catch a day where revenue
    looks normal but orders and customers both moved oddly.

Machine learning is deliberately *not* the default. On a 40-point daily revenue
series an Isolation Forest is both slower and less interpretable than a rolling
z-score, and interpretability is the whole point of this product.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from datetime import datetime
from typing import Any

import numpy as np
import pandas as pd

from app.analytics.context import DatasetContext, pct_change
from app.analytics.timeseries import TimeSeries
from app.analytics.types import Grain, Unit, jsonable

# Minimum points before a claim about "normal" is defensible at all.
MIN_POINTS = 14
# Trailing window for the rolling baseline.
DEFAULT_WINDOW = 7
# Deviations beyond this many standard deviations are flagged.
DEFAULT_THRESHOLD = 3.0
# Below this relative deviation an anomaly is statistically real but
# commercially irrelevant, and surfacing it would only create noise.
MIN_RELATIVE_DEVIATION = 0.15


@dataclass(slots=True)
class AnomalyPoint:
    period: str
    occurred_at: datetime
    metric_key: str
    metric_label: str
    observed: float
    expected: float
    lower_bound: float | None
    upper_bound: float | None
    deviation_pct: float
    z_score: float | None
    direction: str
    severity: str
    method: str
    score: float
    grain: str
    context: dict[str, Any] = field(default_factory=dict)

    def to_dict(self) -> dict[str, Any]:
        return jsonable(
            {
                "period": self.period,
                "occurred_at": self.occurred_at,
                "metric_key": self.metric_key,
                "metric_label": self.metric_label,
                "observed": self.observed,
                "expected": self.expected,
                "lower_bound": self.lower_bound,
                "upper_bound": self.upper_bound,
                "deviation_pct": self.deviation_pct,
                "z_score": self.z_score,
                "direction": self.direction,
                "severity": self.severity,
                "method": self.method,
                "score": self.score,
                "grain": self.grain,
                "context": self.context,
            }
        )

    @property
    def headline(self) -> str:
        movement = "above" if self.direction == "up" else "below"
        return (
            f"{self.metric_label} on {self.period} was "
            f"{abs(self.deviation_pct):.1f}% {movement} the expected range."
        )


def _severity(deviation_pct: float, z_score: float | None) -> tuple[str, float]:
    """Grade an anomaly by how far it deviates, in both relative and statistical terms.

    Both signals matter: a 60% drop is serious regardless of variance, and a
    small drop in a normally rock-steady series is also worth knowing about.
    """
    magnitude = abs(deviation_pct)
    z = abs(z_score) if z_score is not None else 0.0

    relative_score = min(magnitude / 60.0, 1.0)
    statistical_score = min(z / 6.0, 1.0)
    score = round(0.6 * relative_score + 0.4 * statistical_score, 4)

    if magnitude >= 50 or z >= 5:
        return "critical", score
    if magnitude >= 30 or z >= 3.5:
        return "high", score
    if magnitude >= 18 or z >= 2.8:
        return "medium", score
    return "low", score


def _parse_period(label: str, grain: Grain) -> datetime:
    """Recover a timestamp from a display label (they are generated by us)."""
    try:
        if grain is Grain.DAY:
            return datetime.strptime(label, "%Y-%m-%d")
        if grain is Grain.WEEK:
            return datetime.strptime(label.replace("Week of ", ""), "%d %b %Y")
        if grain is Grain.MONTH:
            return datetime.strptime(label, "%b %Y")
        quarter, year = label.split()
        month = (int(quarter[1]) - 1) * 3 + 1
        return datetime(int(year), month, 1)
    except (ValueError, IndexError):
        return datetime(1970, 1, 1)


def detect_rolling_zscore(
    series: TimeSeries,
    *,
    window: int = DEFAULT_WINDOW,
    threshold: float = DEFAULT_THRESHOLD,
) -> list[AnomalyPoint]:
    """Flag points that deviate from their own trailing baseline."""
    values = np.asarray(series.values, dtype="float64")
    if len(values) < MIN_POINTS:
        return []

    window = max(3, min(window, len(values) // 3))
    frame = pd.Series(values)
    # `closed="left"` excludes the point being tested from its own baseline,
    # without which a large outlier partially masks itself.
    rolling = frame.rolling(window=window, min_periods=max(3, window // 2), closed="left")
    baseline = rolling.mean()
    deviation = rolling.std(ddof=0)

    # A series that is genuinely flat has zero rolling std, which would make
    # every tiny wobble infinitely anomalous. Fall back to the global spread.
    global_std = float(np.std(values))
    deviation = deviation.replace(0.0, np.nan).fillna(global_std if global_std > 0 else np.nan)

    anomalies: list[AnomalyPoint] = []
    for index in range(len(values)):
        expected = baseline.iloc[index]
        spread = deviation.iloc[index]
        if pd.isna(expected) or pd.isna(spread) or spread <= 0:
            continue

        observed = values[index]
        z = float((observed - expected) / spread)
        if abs(z) < threshold:
            continue

        relative = abs(observed - expected) / abs(expected) if expected else 0.0
        if relative < MIN_RELATIVE_DEVIATION:
            continue

        deviation_pct = pct_change(observed, float(expected))
        if deviation_pct is None:
            continue

        severity, score = _severity(deviation_pct, z)
        anomalies.append(
            AnomalyPoint(
                period=series.points[index].period,
                occurred_at=_parse_period(series.points[index].period, series.grain),
                metric_key=series.metric_key,
                metric_label=series.metric_label,
                observed=observed,
                expected=float(expected),
                lower_bound=float(expected - threshold * spread),
                upper_bound=float(expected + threshold * spread),
                deviation_pct=round(deviation_pct, 2),
                z_score=round(z, 3),
                direction="up" if z > 0 else "down",
                severity=severity,
                method="rolling_zscore",
                score=score,
                grain=series.grain.value,
                context={
                    "window": window,
                    "threshold": threshold,
                    "rows_in_period": series.points[index].row_count,
                    "explanation": (
                        f"Compared with the average of the previous {window} "
                        f"{series.grain.label} periods."
                    ),
                },
            )
        )
    return anomalies


def detect_iqr(series: TimeSeries, *, multiplier: float = 1.8) -> list[AnomalyPoint]:
    """Interquartile-range outliers — robust, and viable on short series."""
    values = np.asarray(series.values, dtype="float64")
    if len(values) < 8:
        return []

    q1, q3 = np.percentile(values, [25, 75])
    iqr = q3 - q1
    if iqr <= 0:
        return []

    lower, upper = q1 - multiplier * iqr, q3 + multiplier * iqr
    median = float(np.median(values))

    anomalies: list[AnomalyPoint] = []
    for index, observed in enumerate(values):
        if lower <= observed <= upper:
            continue
        deviation_pct = pct_change(float(observed), median)
        if deviation_pct is None or abs(deviation_pct) < MIN_RELATIVE_DEVIATION * 100:
            continue
        severity, score = _severity(deviation_pct, None)
        anomalies.append(
            AnomalyPoint(
                period=series.points[index].period,
                occurred_at=_parse_period(series.points[index].period, series.grain),
                metric_key=series.metric_key,
                metric_label=series.metric_label,
                observed=float(observed),
                expected=median,
                lower_bound=float(lower),
                upper_bound=float(upper),
                deviation_pct=round(deviation_pct, 2),
                z_score=None,
                direction="up" if observed > upper else "down",
                severity=severity,
                method="iqr",
                score=score,
                grain=series.grain.value,
                context={
                    "q1": float(q1),
                    "q3": float(q3),
                    "multiplier": multiplier,
                    "rows_in_period": series.points[index].row_count,
                    "explanation": "Compared with the typical range across the whole period.",
                },
            )
        )
    return anomalies


def detect_multivariate(
    series_map: dict[str, TimeSeries], *, contamination: float = 0.05
) -> list[AnomalyPoint]:
    """Isolation Forest across several metrics measured on the same periods.

    Only worth running when there are at least three metrics and enough history
    to fit on; otherwise it finds structure that is not there.
    """
    usable = {
        key: series
        for key, series in series_map.items()
        if series.points and len(series.points) >= 30
    }
    if len(usable) < 3:
        return []

    periods = [point.period for point in next(iter(usable.values())).points]
    if any([point.period for point in series.points] != periods for series in usable.values()):
        return []

    matrix = np.column_stack([np.asarray(series.values, dtype="float64") for series in usable.values()])
    if not np.isfinite(matrix).all():
        return []

    try:
        from sklearn.ensemble import IsolationForest
        from sklearn.preprocessing import StandardScaler
    except ImportError:  # pragma: no cover - scikit-learn is a hard dependency
        return []

    scaled = StandardScaler().fit_transform(matrix)
    model = IsolationForest(
        contamination=contamination, random_state=42, n_estimators=200
    )
    predictions = model.fit_predict(scaled)
    scores = model.score_samples(scaled)

    primary_key = "revenue" if "revenue" in usable else next(iter(usable))
    primary = usable[primary_key]
    baseline = float(np.mean(primary.values))

    anomalies: list[AnomalyPoint] = []
    for index, prediction in enumerate(predictions):
        if prediction != -1:
            continue
        observed = primary.values[index]
        deviation_pct = pct_change(observed, baseline)
        if deviation_pct is None or abs(deviation_pct) < MIN_RELATIVE_DEVIATION * 100:
            continue
        severity, score = _severity(deviation_pct, None)
        anomalies.append(
            AnomalyPoint(
                period=primary.points[index].period,
                occurred_at=_parse_period(primary.points[index].period, primary.grain),
                metric_key=primary_key,
                metric_label=primary.metric_label,
                observed=observed,
                expected=baseline,
                lower_bound=None,
                upper_bound=None,
                deviation_pct=round(deviation_pct, 2),
                z_score=None,
                direction="up" if observed > baseline else "down",
                severity=severity,
                method="isolation_forest",
                score=round(min(score + 0.1, 1.0), 4),
                grain=primary.grain.value,
                context={
                    "metrics_considered": list(usable.keys()),
                    "isolation_score": round(float(scores[index]), 4),
                    "explanation": (
                        "This period looked unusual when "
                        f"{', '.join(usable.keys())} were considered together."
                    ),
                },
            )
        )
    return anomalies


def choose_method(series: TimeSeries) -> str:
    """Pick a detector from the shape of the data, not from fashion."""
    count = len(series.points)
    if count < 8:
        return "none"
    if count < MIN_POINTS:
        return "iqr"
    return "rolling_zscore"


def detect_anomalies(
    ctx: DatasetContext,
    series_map: dict[str, TimeSeries],
    *,
    max_results: int = 25,
) -> list[AnomalyPoint]:
    """Run detection across every available metric series and rank the results."""
    found: list[AnomalyPoint] = []

    for series in series_map.values():
        if not series.sufficiency.ok or not series.points:
            continue
        method = choose_method(series)
        if method == "rolling_zscore":
            found.extend(detect_rolling_zscore(series))
        elif method == "iqr":
            found.extend(detect_iqr(series))

    found.extend(detect_multivariate(series_map))

    # De-duplicate: the same period flagged for the same metric by two methods is
    # one event. Keep the highest-scoring version.
    best: dict[tuple[str, str], AnomalyPoint] = {}
    for anomaly in found:
        key = (anomaly.metric_key, anomaly.period)
        if key not in best or anomaly.score > best[key].score:
            best[key] = anomaly

    ranked = sorted(
        best.values(), key=lambda a: (a.score, abs(a.deviation_pct)), reverse=True
    )

    # A single business event moves several metrics at once: a flash sale spikes
    # orders, units, customers, and revenue on the same day. Reporting that as
    # four separate anomalies buries the signal, so we keep the strongest one
    # per (period, direction) and list the others as corroboration on it.
    collapsed: list[AnomalyPoint] = []
    seen: dict[tuple[str, str], AnomalyPoint] = {}
    for anomaly in ranked:
        key = (anomaly.period, anomaly.direction)
        primary = seen.get(key)
        if primary is None:
            seen[key] = anomaly
            anomaly.context = {**anomaly.context, "also_affected": []}
            collapsed.append(anomaly)
        else:
            primary.context["also_affected"].append(
                {
                    "metric_key": anomaly.metric_key,
                    "metric_label": anomaly.metric_label,
                    "observed": anomaly.observed,
                    "expected": anomaly.expected,
                    "deviation_pct": anomaly.deviation_pct,
                }
            )

    return collapsed[:max_results]


def summarize_anomalies(anomalies: list[AnomalyPoint]) -> dict[str, Any]:
    if not anomalies:
        return {
            "count": 0,
            "description": "No unusual periods were detected in this dataset.",
        }

    by_severity: dict[str, int] = {}
    for anomaly in anomalies:
        by_severity[anomaly.severity] = by_severity.get(anomaly.severity, 0) + 1

    drops = [a for a in anomalies if a.direction == "down"]
    spikes = [a for a in anomalies if a.direction == "up"]
    most_severe = max(anomalies, key=lambda a: a.score)

    return jsonable(
        {
            "count": len(anomalies),
            "by_severity": by_severity,
            "drops": len(drops),
            "spikes": len(spikes),
            "most_severe": most_severe.to_dict(),
            "description": (
                f"{len(anomalies)} unusual period(s) detected: {len(drops)} below "
                f"the expected range and {len(spikes)} above it."
            ),
        }
    )
